function round1(value: number): number {
  return Math.round(value * 10) / 10
}

/** Producto de biblioteca equivalente a un alimento propio del usuario. */
export function productoDePersonalizado(food: CustomFood): LibraryProduct {
  const factor = 100 / Math.max(1, food.portionGrams)
  return {
    id: food.id,
    name: food.name,
    brand: food.brand ?? "Propio",
    chain: "personal",
    section: SECTION_BY_CATEGORY[food.category],
    category: food.category,
    per100: {
      kcal: Math.round(food.kcal * factor),
      protein: round1(food.protein * factor),
      carbs: round1(food.carbs * factor),
      fat: round1(food.fat * factor),
    },
    portionGrams: food.portionGrams,
    tags: [],
    planEligible: true,
    customSource: food.source ?? "manual",
    barcode: food.barcode,
  }
}

/** Catálogo curado + alimentos propios, sin los productos remotos. */
export function productosLocales(customFoods: CustomFood[]): LibraryProduct[] {
  return [...customFoods.map(productoDePersonalizado), ...PRODUCTS]
}

/**
 * Catálogo completo para el plan y los favoritos: alimentos propios, catálogo
 * curado y los productos remotos ya consultados (para que un
 * favorito de la API siga entrando en el menú y en la compra).
 */
export function productosConPersonalizados(
  customFoods: CustomFood[],
): LibraryProduct[] {
  return [...productosLocales(customFoods), ...productosRemotosCache()]
}

export function productoPorId(
  id: string,
  customFoods: CustomFood[] = [],
): LibraryProduct | undefined {
  const propio = customFoods.find((food) => food.id === id)
  if (propio) return productoDePersonalizado(propio)
  const curado = PRODUCTS.find((product) => product.id === id)
  if (curado) return curado
  return productoRemotoPorId(id)
}

/** Convierte un producto de la biblioteca al formato del motor del plan. */
export function alimentoDeProducto(product: LibraryProduct): Food {
  return {
    id: product.id,
    name: product.name,
    category: product.category,
    shop: SECTION_SHOP[product.section],
    per100: product.per100,
    tags: product.tags,
    slots: SECTION_SLOTS[product.section],
    step: 5,
    unit:
      product.id === "gen-huevo"
        ? { grams: 60, singular: "huevo", plural: "huevos" }
        : undefined,
  }
}

/** Alimentos favoritos listos para pasárselos a `generarPlan`. */
export function alimentosDeFavoritos(
  favoriteIds: string[],
  customFoods: CustomFood[] = [],
): Food[] {
  const byId = new Map(
    productosConPersonalizados(customFoods).map((product) => [
      product.id,
      product,
    ]),
  )
  return favoriteIds
    .map((id) => byId.get(id))
    .filter(
      (product): product is LibraryProduct =>
        Boolean(product) && Boolean(product?.planEligible),
    )
    .map((product) => alimentoDeProducto(product))
}

/** Macros de una ración concreta, redondeados como en el resto de la app. */
export function macrosDeProducto(product: LibraryProduct, grams: number): {
  kcal: number
  protein: number
  carbs: number
  fat: number
} {
  const factor = Math.max(0, grams) / 100
  return {
    kcal: Math.round(product.per100.kcal * factor),
    protein: round1(product.per100.protein * factor),
    carbs: round1(product.per100.carbs * factor),
    fat: round1(product.per100.fat * factor),
  }
}

/** Búsqueda sin acentos ni mayúsculas. */
export function normalizarTexto(texto: string): string {
  return texto
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .trim()
}

export function buscarProductos(
  products: LibraryProduct[],
  query: string,
  chain: ChainId | "todas-las-cadenas",
  section: LibrarySection | "todas-las-secciones",
): LibraryProduct[] {
  const needle = normalizarTexto(query)
  return products.filter((product) => {
    if (
      chain !== "todas-las-cadenas" &&
      product.chain !== chain &&
      product.chain !== "todas"
    ) {
      return false
    }
    if (section !== "todas-las-secciones" && product.section !== section) {
      return false
    }
    if (!needle) return true
    const chainName =
      product.chain === "personal"
        ? "propio"
        : product.chain === "todas"
          ? "generico"
          : product.chain === "remota"
            ? "forma"
            : (SUPERMARKETS.find((market) => market.id === product.chain)
                ?.name ?? product.chain)
    return normalizarTexto(
      `${product.name} ${product.brand} ${chainName} ${product.barcode ?? ""} ${product.tags.join(" ")}`,
    ).includes(needle)
  })
}

/**
 * Categoría del plan a partir de los macros por 100 g.
 *
 * Se usa con lo que llega del escáner, que no trae categoría. Manda la energía
 * que aporta cada macro (4 kcal/g las proteínas y los carbos, 9 kcal/g la
 * grasa), no los gramos: así un aceite (100 g de grasa, 0 de todo lo demás) no
 * acaba clasificado como «proteína» por empate a cero.
 */
export function categoriaDeMacros(per100: {
  protein: number
  carbs: number
  fat: number
}): CustomFoodCategory {
  const proteina = Math.max(0, per100.protein) * 4
  const carbos = Math.max(0, per100.carbs) * 4
  const grasa = Math.max(0, per100.fat) * 9
  if (proteina + carbos + grasa === 0) return "carb"
  if (grasa >= proteina && grasa >= carbos) return "fat"
  if (proteina >= carbos) return "protein"
  return "carb"
}

/**
 * Convierte valores por 100 g en la ración que se guarda en «Mis alimentos».
 * `CustomFood` guarda los valores de la ración, así que aquí se escalan.
 */
export function alimentoDesdePer100(entrada: {
  name: string
  per100: Macro
  grams: number
  source: CustomFoodSource
  brand?: string
  barcode?: string
}): Omit<CustomFood, "id"> {
  const grams = Math.max(1, Math.round(entrada.grams))
  const factor = grams / 100
  return {
    name: entrada.name.trim(),
    category: categoriaDeMacros(entrada.per100),
    portionGrams: grams,
    kcal: Math.round(entrada.per100.kcal * factor),
    protein: round1(entrada.per100.protein * factor),
    carbs: round1(entrada.per100.carbs * factor),
    fat: round1(entrada.per100.fat * factor),
    source: entrada.source,
    brand: entrada.brand?.trim() || undefined,
    barcode: entrada.barcode?.trim() || undefined,
  }
}

/** Guarda un producto del catálogo o de la base remota como alimento propio. */
export function alimentoDesdeProducto(
  product: LibraryProduct,
  source: CustomFoodSource,
  grams = product.portionGrams,
): Omit<CustomFood, "id"> {
  const base = alimentoDesdePer100({
    name: product.name,
    per100: product.per100,
    grams,
    source,
    brand:
      product.brand === "Genérico" || product.brand === "Propio"
        ? undefined
        : product.brand,
    barcode: product.barcode,
  })
  // La categoría del catálogo es más fiable que deducirla de los macros.
  return { ...base, category: product.category }
}
