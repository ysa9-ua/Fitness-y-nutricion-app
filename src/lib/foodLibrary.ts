const NO_PLAN_SECTIONS: LibrarySection[] = ["snacks", "bebidas"]

function p(
  id: string,
  name: string,
  brand: string,
  chain: ChainId,
  section: LibrarySection,
  category: FoodCategory,
  kcal: number,
  protein: number,
  carbs: number,
  fat: number,
  portionGrams: number,
  tags: string[] = [],
): LibraryProduct {
  return {
    id,
    name,
    brand,
    chain,
    section,
    category,
    per100: { kcal, protein, carbs, fat },
    portionGrams,
    tags,
    planEligible: !NO_PLAN_SECTIONS.includes(section),
  }
}

